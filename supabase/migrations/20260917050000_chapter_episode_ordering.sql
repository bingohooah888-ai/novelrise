grant execute on function public.novelight_create_novel_chapter(bigint, text) to authenticated;
grant execute on function public.novelight_rename_novel_chapter(bigint, text) to authenticated;
grant execute on function public.novelight_delete_novel_chapter(bigint) to authenticated;
grant execute on function public.novelight_reorder_novel_structure(bigint, jsonb, jsonb) to authenticated;
