-- NOVELIGHT competitor-audit item #5: author-managed novel series.
-- Series group works for navigation only. They do not create a second
-- evaluation, ranking, PV, favorite, LIGHT SEED, or exposure unit.

begin;

select pg_advisory_xact_lock(hashtext('novelight:20260917040000-novel-series'));

create table public.novel_series (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  description text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint novel_series_title_length check (
    char_length(btrim(title)) between 1 and 120
  ),
  constraint novel_series_description_length check (
    char_length(description) <= 2000
  )
);

create table public.novel_series_items (
  series_id bigint not null references public.novel_series(id) on delete cascade,
  novel_id bigint not null references public.novels(id) on delete cascade,
  position integer not null,
  created_at timestamptz not null default now(),
  primary key (series_id, novel_id),
  constraint novel_series_items_novel_once unique (novel_id),
  constraint novel_series_items_position_once unique (series_id, position),
  constraint novel_series_items_positive_position check (position > 0)
);

create index novel_series_user_id_idx on public.novel_series(user_id);
create index novel_series_items_series_position_idx
  on public.novel_series_items(series_id, position);

alter table public.novel_series enable row level security;
alter table public.novel_series_items enable row level security;

