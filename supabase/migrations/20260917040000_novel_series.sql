create or replace function public.novelight_set_series_items(
  p_series_id bigint,
  p_novel_ids bigint[] default '{}'::bigint[]
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid uuid := auth.uid();
  v_owner uuid;
  v_count integer := coalesce(cardinality(p_novel_ids), 0);
begin
  if v_uid is null then
    raise exception 'AUTH_REQUIRED' using errcode = '42501';
  end if;

  select s.user_id
    into v_owner
    from public.novel_series s
   where s.id = p_series_id
   for update;

  if v_owner is null or v_owner <> v_uid then
    raise exception 'SERIES_NOT_FOUND' using errcode = '42501';
  end if;

  if v_count > 100 then
    raise exception 'SERIES_ITEM_LIMIT';
  end if;

  if exists (select 1 from unnest(p_novel_ids) as x(novel_id) where novel_id is null) then
    raise exception 'SERIES_ITEM_INVALID';
  end if;

  if (
    select count(*)
      from unnest(p_novel_ids) as x(novel_id)
  ) <> (
    select count(distinct novel_id)
      from unnest(p_novel_ids) as x(novel_id)
  ) then
    raise exception 'SERIES_ITEM_DUPLICATE';
  end if;

  if (
    select count(*)
      from public.novels n
     where n.id = any(p_novel_ids)
       and n.user_id = v_uid
  ) <> v_count then
    raise exception 'SERIES_ITEM_NOT_OWNED' using errcode = '42501';
  end if;

  if exists (
    select 1
      from public.novel_series_items existing
     where existing.novel_id = any(p_novel_ids)
       and existing.series_id <> p_series_id
  ) then
    raise exception 'NOVEL_ALREADY_IN_SERIES';
  end if;

  delete from public.novel_series_items
   where series_id = p_series_id;

  insert into public.novel_series_items (series_id, novel_id, position)
  select p_series_id, item.novel_id, item.ordinality::integer
    from unnest(p_novel_ids) with ordinality as item(novel_id, ordinality);

  update public.novel_series
     set updated_at = now()
   where id = p_series_id;
end;
$$;

revoke all on function public.novelight_set_series_items(bigint, bigint[]) from public, anon, authenticated;
grant execute on function public.novelight_set_series_items(bigint, bigint[]) to authenticated;
grant execute on function public.novelight_set_series_items(bigint, bigint[]) to service_role;

create or replace function public.novelight_public_series_context(p_novel_id bigint)
returns table (
  series_id bigint,
  series_title text,
  series_description text,
  item_novel_id bigint,
  item_title text,
  item_position integer,
  is_current boolean
)
language sql
stable
security definer
set search_path = ''
as $$
  with target as (
    select n.id, n.user_id, n.status
      from public.novels n
     where n.id = p_novel_id
       and (
         n.status = 'published'
         or (
           auth.uid() is not null
           and n.user_id = auth.uid()
         )
       )
  ), target_series as (
    select i.series_id
      from public.novel_series_items i
      join target t on t.id = i.novel_id
     limit 1
  )
  select
    s.id,
    s.title,
    s.description,
    n.id,
    n.title,
    i.position,
    n.id = p_novel_id
  from target_series ts
  join public.novel_series s on s.id = ts.series_id
  join public.novel_series_items i on i.series_id = s.id
  join public.novels n on n.id = i.novel_id
  where
    n.status = 'published'
    or (
      auth.uid() is not null
      and n.user_id = auth.uid()
      and s.user_id = auth.uid()
    )
  order by i.position asc;
$$;

revoke all on function public.novelight_public_series_context(bigint) from public, anon, authenticated;
grant execute on function public.novelight_public_series_context(bigint) to anon, authenticated;
grant execute on function public.novelight_public_series_context(bigint) to service_role;

